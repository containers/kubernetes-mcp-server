// Command export converts the in-tree toolsets into Tool custom resources.
//
// For every tool of the selected toolsets it takes the real MCP contract
// (name, description, input schema, annotations) from the registered Go
// definition and pairs it with a declaratively described action. Every tool
// must either be converted or be listed as skipped with a reason, so the
// output doubles as an honest inventory of what a Tool resource can and
// cannot express today.
//
//	go run ./examples/dynamic-tools/hack/export [output dir]
package main

import (
	"context"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"

	metav1 "k8s.io/apimachinery/pkg/apis/meta/v1"
	"k8s.io/utils/ptr"
	"sigs.k8s.io/yaml"

	"github.com/containers/kubernetes-mcp-server/pkg/api"
	"github.com/containers/kubernetes-mcp-server/pkg/toolsets"
	"github.com/containers/kubernetes-mcp-server/pkg/toolsets/dynamic"

	// Register every in-tree toolset.
	_ "github.com/containers/kubernetes-mcp-server/pkg/mcp"
)

const (
	urlSentinel = "https://__URL__"
	caSentinel  = "__CA__"
)

// conversion describes how one in-tree tool becomes one Tool resource. Name,
// Description and InputSchema override the source contract when the port has
// to narrow it; Note documents every behavioral difference.
type conversion struct {
	Name        string
	Description string
	InputSchema any
	Kubernetes  *dynamic.KubernetesAction
	HTTP        *dynamic.HTTPAction
	Steps       []dynamic.Step
	Output      string
	Note        string
}

type plan struct {
	toolset string
	// chart is the Helm chart directory name; empty means plain manifests
	// under converted/<toolset>.
	chart   string
	tools   map[string][]conversion
	skipped map[string]string
	// prompts ports in-tree prompts by name; extraPrompts have no in-tree
	// counterpart; skippedPrompts lists the rest with a reason.
	prompts        map[string][]promptConversion
	extraPrompts   []promptConversion
	skippedPrompts map[string]string
	// skipPromptsReason skips every prompt not listed in prompts.
	skipPromptsReason string
}

type manifest struct {
	APIVersion string `json:"apiVersion"`
	Kind       string `json:"kind"`
	Metadata   struct {
		Name   string            `json:"name"`
		Labels map[string]string `json:"labels,omitempty"`
	} `json:"metadata"`
	Spec dynamic.ToolSpec `json:"spec"`
}

type reportRow struct {
	tool, result, note string
}

func main() {
	outDir := "examples/dynamic-tools"
	if len(os.Args) > 1 {
		outDir = os.Args[1]
	}
	ctx := context.Background()
	var report strings.Builder
	report.WriteString("# Conversion report\n\nGenerated by `go run ./examples/dynamic-tools/hack/export`. One row per in-tree tool.\n")
	total, converted := 0, 0
	for _, p := range plans() {
		toolset := toolsets.ToolsetFromString(p.toolset)
		if toolset == nil {
			fail("unknown toolset %q", p.toolset)
		}
		var manifests []manifest
		var rows []reportRow
		for _, tool := range toolset.GetTools(ctx, api.ToolsetContext{Inspector: &documentationInspector{}}) {
			total++
			name := tool.Tool.Name
			conversions, ok := p.tools[name]
			if !ok {
				reason, skipped := p.skipped[name]
				if !skipped {
					fail("toolset %s: tool %s is neither converted nor skipped", p.toolset, name)
				}
				rows = append(rows, reportRow{name, "no", reason})
				continue
			}
			converted++
			for _, c := range conversions {
				m, err := convert(p.toolset, tool, c)
				if err != nil {
					fail("toolset %s: tool %s: %v", p.toolset, name, err)
				}
				manifests = append(manifests, m)
				result := "yes"
				if m.Spec.Name != name {
					result = "yes, as `" + m.Spec.Name + "`"
				}
				rows = append(rows, reportRow{name, result, c.Note})
			}
			delete(p.tools, name)
		}
		for name := range p.tools {
			fail("toolset %s: conversion declared for unknown tool %s", p.toolset, name)
		}
		if err := write(outDir, p, manifests); len(manifests) > 0 && err != nil {
			fail("toolset %s: %v", p.toolset, err)
		}
		var promptManifests []promptManifest
		for _, prompt := range toolset.GetPrompts(ctx, api.ToolsetContext{Inspector: &documentationInspector{}}) {
			total++
			name := prompt.Prompt.Name
			conversions, ok := p.prompts[name]
			if !ok {
				reason, skipped := p.skippedPrompts[name]
				if !skipped && p.skipPromptsReason != "" {
					reason, skipped = p.skipPromptsReason, true
				}
				if !skipped {
					fail("toolset %s: prompt %s is neither converted nor skipped", p.toolset, name)
				}
				rows = append(rows, reportRow{name + " (prompt)", "no", reason})
				continue
			}
			converted++
			for _, c := range conversions {
				c = withPromptContract(prompt, c)
				m, err := promptManifestOf(p.toolset, c)
				if err != nil {
					fail("toolset %s: prompt %s: %v", p.toolset, name, err)
				}
				promptManifests = append(promptManifests, m)
				rows = append(rows, reportRow{name + " (prompt)", "yes", c.Note})
			}
			delete(p.prompts, name)
		}
		for name := range p.prompts {
			fail("toolset %s: conversion declared for unknown prompt %s", p.toolset, name)
		}
		for _, c := range p.extraPrompts {
			m, err := promptManifestOf(p.toolset, c)
			if err != nil {
				fail("toolset %s: prompt %s: %v", p.toolset, c.Name, err)
			}
			promptManifests = append(promptManifests, m)
			rows = append(rows, reportRow{c.Name + " (prompt)", "new", c.Note})
		}
		if err := writePrompts(outDir, p, promptManifests); err != nil {
			fail("toolset %s: %v", p.toolset, err)
		}
		fmt.Fprintf(&report, "\n## %s\n\n| Tool | Converted | Notes |\n|------|-----------|-------|\n", p.toolset)
		for _, row := range rows {
			fmt.Fprintf(&report, "| `%s` | %s | %s |\n", row.tool, row.result, row.note)
		}
	}
	fmt.Fprintf(&report, "\n**%d of %d tools and prompts converted.**\n", converted, total)
	if err := os.WriteFile(filepath.Join(outDir, "conversion-report.md"), []byte(report.String()), 0o644); err != nil {
		fail("%v", err)
	}
	fmt.Printf("converted %d of %d tools, report in %s\n", converted, total, filepath.Join(outDir, "conversion-report.md"))
}

func convert(toolsetName string, tool api.ServerTool, c conversion) (manifest, error) {
	var m manifest
	m.APIVersion = dynamic.Group + "/" + dynamic.Version
	m.Kind = dynamic.Kind
	m.Spec = dynamic.ToolSpec{
		Name:        tool.Tool.Name,
		Title:       tool.Tool.Annotations.Title,
		Description: tool.Tool.Description,
		ReadOnly:    ptr.Deref(tool.Tool.Annotations.ReadOnlyHint, false),
		Destructive: ptr.Deref(tool.Tool.Annotations.DestructiveHint, false),
		Idempotent:  ptr.Deref(tool.Tool.Annotations.IdempotentHint, false),
		Kubernetes:  c.Kubernetes,
		HTTP:        c.HTTP,
		Steps:       c.Steps,
		Output:      c.Output,
	}
	if c.Name != "" {
		m.Spec.Name = c.Name
	}
	if c.Description != "" {
		m.Spec.Description = c.Description
	}
	schema := c.InputSchema
	if schema == nil {
		schema = tool.Tool.InputSchema
	}
	if schema != nil {
		raw, err := json.Marshal(schema)
		if err != nil {
			return m, fmt.Errorf("input schema: %w", err)
		}
		m.Spec.InputSchema = raw
	}
	m.Metadata.Name = strings.ReplaceAll(m.Spec.Name, "_", "-")
	m.Metadata.Labels = map[string]string{
		"app.kubernetes.io/part-of":                     "kubernetes-mcp-server",
		"tools.kubernetes-mcp-server.io/source-toolset": toolsetName,
	}
	// Validate exactly what the server will load, with the Helm placeholders
	// replaced by legal values.
	check := dynamic.Tool{Metadata: dynamic.Metadata{Name: m.Metadata.Name}, Spec: m.Spec}
	if check.Spec.HTTP != nil && check.Spec.HTTP.URL == urlSentinel {
		httpCopy := *check.Spec.HTTP
		httpCopy.URL = "https://placeholder.invalid"
		httpCopy.CertificateAuthority = ""
		check.Spec.HTTP = &httpCopy
	}
	if err := dynamic.Check(check); err != nil {
		return m, err
	}
	return m, nil
}

var (
	urlLine      = regexp.MustCompile(`(?m)^(\s*)url: ` + regexp.QuoteMeta(urlSentinel) + `$`)
	caLine       = regexp.MustCompile(`(?m)^(\s*)certificateAuthority: ` + caSentinel + `$`)
	insecureLine = regexp.MustCompile(`(?m)^(\s*)insecureSkipTLSVerify: true$`)
)

func write(outDir string, p plan, manifests []manifest) error {
	if len(manifests) == 0 {
		return nil
	}
	var out strings.Builder
	out.WriteString("# Code generated by examples/dynamic-tools/hack/export from the in-tree " + p.toolset + " toolset. DO NOT EDIT.\n")
	for _, m := range manifests {
		raw, err := yaml.Marshal(m)
		if err != nil {
			return err
		}
		text := string(raw)
		if p.chart != "" {
			text = urlLine.ReplaceAllString(text, "${1}url: {{ .Values.url | quote }}")
			text = caLine.ReplaceAllString(text, "${1}certificateAuthority: {{ .Values.certificateAuthority | quote }}")
			text = insecureLine.ReplaceAllString(text, "${1}insecureSkipTLSVerify: {{ .Values.insecureSkipTLSVerify }}")
		}
		out.WriteString("---\n" + text)
	}
	var path string
	if p.chart != "" {
		path = filepath.Join(outDir, "charts", p.chart, "templates", "tools.yaml")
	} else {
		path = filepath.Join(outDir, "converted", p.toolset+".yaml")
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, []byte(out.String()), 0o644)
}

// withPromptContract fills the Prompt contract from the in-tree definition
// unless the conversion overrides it.
func withPromptContract(prompt api.ServerPrompt, c promptConversion) promptConversion {
	if c.Name == "" {
		c.Name = prompt.Prompt.Name
	}
	if c.Title == "" {
		c.Title = prompt.Prompt.Title
	}
	if c.Description == "" {
		c.Description = prompt.Prompt.Description
	}
	if c.Arguments == nil {
		for _, argument := range prompt.Prompt.Arguments {
			c.Arguments = append(c.Arguments, dynamic.PromptArgument{Name: argument.Name, Description: argument.Description, Required: argument.Required})
		}
	}
	return c
}

