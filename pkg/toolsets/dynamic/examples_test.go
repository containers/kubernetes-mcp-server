// ExamplesSuite keeps every Tool definition shipped under examples/dynamic-tools
// valid: hand-written examples, the converted manifests and the rendered Helm charts
// must all parse, validate and compile their CEL expressions.
type ExamplesSuite struct {
	suite.Suite
	root string
}

func (s *ExamplesSuite) SetupSuite() {
	s.root = filepath.Join("..", "..", "..", "examples", "dynamic-tools")
}

func (s *ExamplesSuite) checkDocuments(name string, content []byte) int {
	count := 0
	for _, doc := range strings.Split(strings.ReplaceAll(string(content), "\r\n", "\n"), "\n---") {
		var header map[string]any
		if err := yaml.Unmarshal([]byte(doc), &header); err != nil || header == nil {
			continue
		}
		switch header["kind"] {
		case Kind:
			var tool Tool
			s.Require().NoError(yaml.Unmarshal([]byte(doc), &tool), "%s: invalid YAML", name)
			s.Require().NoError(Check(tool), "%s: tool %s", name, tool.Metadata.Name)
		case PromptKind:
			var prompt Prompt
			s.Require().NoError(yaml.Unmarshal([]byte(doc), &prompt), "%s: invalid YAML", name)
			s.Require().NoError(CheckPrompt(prompt), "%s: prompt %s", name, prompt.Metadata.Name)
		default:
			continue
		}
		count++
		s.Equal(Group+"/"+Version, header["apiVersion"], "%s", name)
	}
	return count
}

func (s *ExamplesSuite) TestHandWrittenExamplesAreValid() {
	files, err := filepath.Glob(filepath.Join(s.root, "tools", "*.yaml"))
	s.Require().NoError(err)
	s.Require().NotEmpty(files)
	for _, file := range files {
		s.Run(filepath.Base(file), func() {
			raw, err := os.ReadFile(file)
			s.Require().NoError(err)
			s.Equal(1, s.checkDocuments(file, raw))
		})
	}
}

func (s *ExamplesSuite) TestExportedManifestsAreValid() {
	files, err := filepath.Glob(filepath.Join(s.root, "converted", "*.yaml"))
	s.Require().NoError(err)
	s.Require().NotEmpty(files)
	for _, file := range files {
		s.Run(filepath.Base(file), func() {
			raw, err := os.ReadFile(file)
			s.Require().NoError(err)
			s.Positive(s.checkDocuments(file, raw))
		})
	}
}

func (s *ExamplesSuite) TestChartsRenderValidTools() {
	helm, err := exec.LookPath("helm")
	if err != nil {
		helm = filepath.Join("..", "..", "..", "_output", "tools", "bin", "helm")
		if _, statErr := os.Stat(helm); statErr != nil {
			s.T().Skip("helm not available (make helm)")
		}
	}
	charts, err := filepath.Glob(filepath.Join(s.root, "charts", "*"))
	s.Require().NoError(err)
	s.Require().NotEmpty(charts)
	for _, chart := range charts {
		s.Run(filepath.Base(chart), func() {
			out, err := exec.Command(helm, "template", "x", chart, "--set", "url=https://example.invalid").CombinedOutput()
			s.Require().NoError(err, string(out))
			s.Positive(s.checkDocuments(chart, out))
		})
	}
}

var generatedBy = regexp.MustCompile(`Code generated by (\S+)`)

func (s *ExamplesSuite) TestManifestsDoNotClaimAMissingGenerator() {
	// A "Code generated ... DO NOT EDIT" header is a promise that the named
	// generator exists and can be re-run. The exporter that produced the
	// charts was removed with the in-tree toolsets, so the files are
	// maintained by hand and must say so.
	var files []string
	s.Require().NoError(filepath.WalkDir(s.root, func(path string, d fs.DirEntry, err error) error {
		if err == nil && !d.IsDir() && strings.HasSuffix(path, ".yaml") {
			files = append(files, path)
		}
		return err
	}))
	s.Require().NotEmpty(files)
	for _, file := range files {
		raw, err := os.ReadFile(file)
		s.Require().NoError(err)
		for _, match := range generatedBy.FindAllStringSubmatch(string(raw), -1) {
			generator := filepath.Join("..", "..", "..", match[1])
			_, err := os.Stat(generator)
			s.NoError(err, "%s claims to be generated by %s, which does not exist", file, match[1])
		}
	}
}

func (s *ExamplesSuite) TestKubeVirtToolsRequireTheVirtualMachineAPI() {
	// The in-tree KubeVirt toolset hid its tools while no target served
	// VirtualMachine; the chart must keep that through `requires`.
	raw, err := os.ReadFile(filepath.Join(s.root, "charts", "kubevirt-mcp-tools", "templates", "tools.yaml"))
	s.Require().NoError(err)
	count := 0
	for _, doc := range strings.Split(strings.ReplaceAll(string(raw), "\r\n", "\n"), "\n---") {
		if !strings.Contains(doc, "kind: Tool") {
			continue
		}
		var tool Tool
		s.Require().NoError(yaml.Unmarshal([]byte(doc), &tool))
		s.Contains(tool.Spec.Requires, GVKRef{APIVersion: "kubevirt.io/v1", Kind: "VirtualMachine"}, "tool %s must declare the VirtualMachine API in spec.requires", tool.Metadata.Name)
		count++
	}
	s.Positive(count)
}

func TestExamples(t *testing.T) {
	suite.Run(t, new(ExamplesSuite))
}
